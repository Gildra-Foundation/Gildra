export function getTalentCalculatorCopy(lang: TalentCopyLang) {
  return talentCalculatorCopy[lang];
}

/** Spec/class names follow the page language; game terms stay as Blizzard ships them. */
export function talentThemeNames(theme: TalentSpecTheme, lang: TalentCopyLang) {
  return lang === "ru"
    ? { spec: theme.specNameRu, className: theme.classNameRu, role: theme.roleRu, resource: theme.resourceLabel, fantasy: theme.fantasy }
    : { spec: theme.specName, className: theme.className, role: roleLabelsEn[theme.role], resource: resourceLabelsEn[theme.resourceLabel] ?? theme.resourceLabel, fantasy: "" };
}

export function heroPathName(hero: { name: string; nameRu: string }, lang: TalentCopyLang) {
  return lang === "ru" ? hero.nameRu : hero.name;
}
