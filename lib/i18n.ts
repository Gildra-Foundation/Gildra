/** t(lang)("View All →") — RU-перевод или исходная строка. */
export const t =
  (lang: Lang) =>
  (s: string): string =>
    lang === "ru" ? (RU[s] ?? s) : s;

/** Navigation labels can differ from the same word in prose (hero "Meta" →
 *  "метой", nav "Meta" → "Мета"): `nav:<key>` wins, then the plain key. */
export const tNav =
  (lang: Lang) =>
  (s: string): string =>
    lang === "ru" ? (RU[`nav:${s}`] ?? RU[s] ?? s) : s;
